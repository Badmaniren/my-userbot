import json
import os
from typing import Any, Dict, Optional, List


class AuditFormatterError(Exception):
    pass


class AuditFormatter:
    def _normalize_report(self, report: Any) -> Dict[str, Any]:
        if isinstance(report, list):
            if not report or not all(isinstance(a, dict) for a in report):
                raise AuditFormatterError("Expected dict or non-empty list of anomaly dicts for report")
            # Если логгер возвращает список аномалий, заворачиваем его в стандартную структуру отчета
            anomalies = report
            severities = {}
            for a in anomalies:
                if isinstance(a, dict) and "severity" in a:
                    sev = a["severity"]
                    severities[sev] = severities.get(sev, 0) + 1
            return {
                "report_id": "rep-generated",
                "total_anomalies": len(anomalies),
                "severity_distribution": severities,
                "anomalies": anomalies,
            }
        if not isinstance(report, dict):
            raise AuditFormatterError(f"Expected dict for report, got {type(report).__name__}")
        return report

    def format_json(self, report: Any, indent: Optional[int] = None) -> str:
        report_dict = self._normalize_report(report)
        try:
            return json.dumps(report_dict, indent=indent, ensure_ascii=False)
        except (TypeError, ValueError) as err:
            raise AuditFormatterError(f"Failed to serialize report to JSON: {err}") from err

    def format_markdown(self, report: Any) -> str:
        report_dict = self._normalize_report(report)

        lines = ["# Audit Report"]

        report_id = report_dict.get("report_id")
        if report_id is not None:
            lines.append(f"- **Report ID:** {report_id}")

        environment = report_dict.get("environment")
        if environment is not None:
            lines.append(f"- **Environment:** {environment}")

        repo_path = report_dict.get("repo_path")
        if repo_path is not None:
            lines.append(f"- **Repo Path:** {repo_path}")

        total_anomalies = report_dict.get("total_anomalies")
        if total_anomalies is not None:
            lines.append(f"- **Total Anomalies:** {total_anomalies}")

        generated_by = report_dict.get("generated_by")
        if generated_by is not None:
            lines.append(f"- **Generated By:** {generated_by}")

        severity_dist = report_dict.get("severity_distribution")
        if isinstance(severity_dist, dict) and severity_dist:
            lines.append("\n## Severity Distribution")
            for sev, count in severity_dist.items():
                lines.append(f"- **{sev}**: {count}")

        anomalies = report_dict.get("anomalies")
        if not isinstance(anomalies, list):
            anomalies = []

        lines.append("\n## Anomalies")
        if not anomalies:
            lines.append("No anomalies reported.")
        else:
            for idx, anom in enumerate(anomalies, 1):
                if not isinstance(anom, dict):
                    continue
                anom_id = anom.get("id", f"anom-{idx}")
                lines.append(f"\n### Anomaly {idx}: {anom_id}")
                if "source" in anom:
                    lines.append(f"- **Source:** {anom['source']}")
                if "severity" in anom:
                    lines.append(f"- **Severity:** {anom['severity']}")
                if "timestamp" in anom:
                    lines.append(f"- **Timestamp:** {anom['timestamp']}")
                if "details" in anom:
                    lines.append(f"- **Details:** {anom['details']}")

                telemetry = anom.get("telemetry_snapshot")
                if not telemetry and isinstance(anom.get("snapshot"), dict):
                    telemetry = anom.get("snapshot")

                if isinstance(telemetry, dict) and telemetry:
                    lines.append("- **Telemetry Snapshot:**")
                    for k, v in telemetry.items():
                        lines.append(f"  - `{k}`: {v}")

        return "\n".join(lines) + "\n"

    def format_summary(self, report: Any) -> str:
        report_dict = self._normalize_report(report)

        lines = ["=== Audit Summary ==="]

        report_id = report_dict.get("report_id")
        if report_id is not None:
            lines.append(f"Report ID: {report_id}")

        total_anomalies = report_dict.get("total_anomalies")
        anomalies = report_dict.get("anomalies")
        if not isinstance(anomalies, list):
            anomalies = []

        if total_anomalies is None:
            total_anomalies = len(anomalies)
        lines.append(f"Total Anomalies: {total_anomalies}")

        severity_dist = report_dict.get("severity_distribution")
        if isinstance(severity_dist, dict) and severity_dist:
            lines.append("Severity Breakdown:")
            for sev, count in severity_dist.items():
                lines.append(f"  - {sev}: {count}")

        if anomalies:
            lines.append("Anomalies List:")
            for anom in anomalies:
                if not isinstance(anom, dict):
                    continue
                parts = []
                if "id" in anom:
                    parts.append(f"[{anom['id']}]")
                if "source" in anom:
                    parts.append(f"source={anom['source']}")
                if "severity" in anom:
                    parts.append(f"severity={anom['severity']}")
                if "details" in anom:
                    parts.append(f"details={anom['details']}")
                lines.append("  " + " | ".join(parts))

        return "\n".join(lines) + "\n"

    def format(self, report: Any, output_format: str = "json", **kwargs) -> str:
        fmt = (output_format or "json").strip().lower()
        if fmt == "json":
            return self.format_json(report, **kwargs)
        elif fmt in ("markdown", "md"):
            return self.format_markdown(report)
        elif fmt in ("summary", "text", "txt"):
            return self.format_summary(report)
        else:
            raise AuditFormatterError(f"Unsupported format: {output_format}")

    def export_to_file(self, report: Any, file_path: str, output_format: str = "json", **kwargs) -> str:
        content = self.format(report, output_format=output_format, **kwargs)
        try:
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)
        except OSError as err:
            raise AuditFormatterError(f"Failed to write file '{file_path}': {err}") from err
        return file_path

    def export_report(self, report: Any, file_path: str, format_type: str = "json", **kwargs) -> str:
        return self.export_to_file(report, file_path=file_path, output_format=format_type, **kwargs)