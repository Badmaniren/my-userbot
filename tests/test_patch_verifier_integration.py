import unittest
import os
import subprocess
import tempfile
import shutil
import uuid
import random
from skills.patch_verifier import GitInspector, LessonParser, PatchExecutor, PatchVerifier

class TestPatchVerifierIntegration(unittest.TestCase):
    def setUp(self):
        self.test_dir = tempfile.mkdtemp()
        subprocess_init = subprocess.run(["git", "init", self.test_dir], capture_output=True, text=True)
        if subprocess_init.returncode != 0:
            subprocess.run(["git", "config", "--global", "init.defaultBranch", "main"], capture_output=True)
            subprocess.run(["git", "init", self.test_dir], check=True)
        
        subprocess.run(["git", "-C", self.test_dir, "config", "user.name", "Test Architect"], check=True)
        subprocess.run(["git", "-C", self.test_dir, "config", "user.email", "architect@test.local"], check=True)
        
        init_file = os.path.join(self.test_dir, "README.md")
        with open(init_file, "w", encoding="utf-8") as f:
            f.write("Initial commit")
        subprocess.run(["git", "-C", self.test_dir, "add", "README.md"], check=True)
        subprocess.run(["git", "-C", self.test_dir, "commit", "-m", "Initial commit"], check=True)

        self.inspector = GitInspector(self.test_dir)
        self.parser = LessonParser(self.inspector)
        self.executor = PatchExecutor(self.test_dir, self.inspector, self.parser)
        self.verifier = PatchVerifier(self.test_dir, self.inspector, self.executor)

    def tearDown(self):
        shutil.rmtree(self.test_dir, ignore_errors=True)

    def test_safe_patch_pipeline_integration(self):
        random_suffix = uuid.uuid4().hex[:8]
        file_name = f"module_{random_suffix}.py"
        random_value = random.randint(1000, 9999)

        valid_code = f"# Autogenerated test module\nVAL = {random_value}\n\ndef compute():\n    return VAL * 2\n"
        commit_msg = f"Add verified module {random_suffix}"

        patch_data = {
            "file_path": file_name,
            "content": valid_code,
            "commit_message": commit_msg
        }

        success = self.verifier.verify_and_apply(patch_data)
        self.assertTrue(success, "Пайнлайн верификации и применения патча должен завершиться успешно для валидного кода.")

        full_path = os.path.join(self.test_dir, file_name)
        self.assertTrue(os.path.exists(full_path), "Файл патча должен реально появиться в репозитории.")

        with open(full_path, "r", encoding="utf-8") as f:
            content = f.read()
        self.assertIn(str(random_value), content, "Содержимое файла должно соответствовать переданному в патче.")

        history = self.inspector.get_commit_history(max_count=2)
        self.assertGreaterEqual(len(history), 2, "История коммитов должна содержать новый коммит патча.")
        self.assertEqual(history[0]["message"], commit_msg, "Сообщение последнего коммита должно совпадать с переданным.")

    def test_invalid_syntax_patch_rejection(self):
        random_suffix = uuid.uuid4().hex[:8]
        file_name = f"broken_{random_suffix}.py"

        invalid_code = "def broken_syntax_func(\n    print('unclosed parenthesis'"
        
        patch_data = {
            "file_path": file_name,
            "content": invalid_code,
            "commit_message": "Should not apply"
        }

        success = self.verifier.verify_and_apply(patch_data)
        self.assertFalse(success, "Пайнлайн должен отклонить патч с синтаксической ошибкой.")

        full_path = os.path.join(self.test_dir, file_name)
        self.assertFalse(os.path.exists(full_path), "Файл с невалидным синтаксисом не должен создаваться в репозитории.")

    def test_positional_args_verify_and_apply(self):
        random_suffix = uuid.uuid4().hex[:8]
        file_name = f"pos_module_{random_suffix}.py"
        valid_code = "x = 42\n"

        success = self.verifier.verify_and_apply(file_name, valid_code)
        self.assertTrue(success)
        full_path = os.path.join(self.test_dir, file_name)
        self.assertTrue(os.path.exists(full_path))

if __name__ == "__main__":
    unittest.main()