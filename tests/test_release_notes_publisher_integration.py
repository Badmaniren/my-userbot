import unittest
import os
import shutil
import uuid
import random
from skills.release_notes_publisher import ReleaseNotesPublisher

class TestReleaseNotesPublisherIntegration(unittest.TestCase):
    
    def setUp(self):
        self.repo_path = f"/tmp/test_repo_{uuid.uuid4().hex}"
        os.makedirs(self.repo_path, exist_ok=True)
        
        # Initialize a basic git repo structure so components work properly
        os.system(f"git -C {self.repo_path} init -b main")
        os.system(f"git -C {self.repo_path} config user.name 'Test Architect'")
        os.system(f"git -C {self.repo_path} config user.email 'architect@test.com'")
        
        # Create a random file and commit it to have history
        self.random_file_name = f"file_{uuid.uuid4().hex}.txt"
        self.file_path = os.path.join(self.repo_path, self.random_file_name)
        self.random_content = f"content_{random.randint(1000, 9999)}"
        
        with open(self.file_path, "w") as f:
            f.write(self.random_content)
            
        os.system(f"git -C {self.repo_path} add {self.random_file_name}")
        os.system(f"git -C {self.repo_path} commit -m 'Initial commit {uuid.uuid4().hex}'")

    def tearDown(self):
        if os.path.exists(self.repo_path):
            shutil.rmtree(self.repo_path)

    def test_release_notes_publisher_composition(self):
        publisher = ReleaseNotesPublisher(self.repo_path)
        
        # Verify component attributes or behavior relying on real integration
        # without mocking release_notes_composer and repo_notifier
        self.assertTrue(hasattr(publisher, 'composer') or hasattr(publisher, 'release_notes_composer'))
        self.assertTrue(hasattr(publisher, 'notifier') or hasattr(publisher, 'repo_notifier'))
        
        output_filename = f"release_notes_{uuid.uuid4().hex}.md"
        output_path = os.path.join(self.repo_path, output_filename)
        
        # Execute publishing which combines composer and notifier
        if hasattr(publisher, 'publish'):
            result = publisher.publish(output_path)
        elif hasattr(publisher, 'run'):
            result = publisher.run()
        else:
            # Fallback to standard execution method if named differently
            result = publisher.compose_and_notify(output_path)
            
        self.assertIsNotNone(result)
        
        # Verify that release notes file was actually generated by the composer skill
        self.assertTrue(os.path.exists(output_path), "Release notes file must be generated by composition")
        
        with open(output_path, "r") as f:
            content = f.read()
            self.assertGreater(len(content), 0, "Generated release notes cannot be empty")

if __name__ == "__main__":
    unittest.main()